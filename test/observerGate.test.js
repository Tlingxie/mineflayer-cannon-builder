const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const { execFile } = require('node:child_process')
const { promisify } = require('node:util')
const run = promisify(execFile)

test('observer gate transforms official bytecode, preserves OFF and falling-edge behavior, and fails closed', async t => {
  let buildObserverGate
  try { ({ buildObserverGate } = require('../scripts/build-observer-gate')) } catch (error) { if (error.code !== 'MODULE_NOT_FOUND') throw error }
  assert.equal(typeof buildObserverGate, 'function')
  try { await fs.access(path.resolve(__dirname, '../.runtime/server/versions/1.21.4/server-1.21.4.jar')) } catch (error) {
    if (error.code !== 'ENOENT') throw error
    t.skip('Official Minecraft 1.21.4 cache is unavailable; this test never downloads it')
    return
  }
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'observer-gate-test-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const built = await buildObserverGate({ outputDirectory: path.join(directory, 'build') })
  const releaseHash = crypto.createHash('sha256').update(`${built.sha256.agent}\n${built.sha256.bridge}\n${built.sha256.tests}\n`).digest('hex')
  assert.equal(path.dirname(built.agentJar), path.join(directory, 'build', 'releases', releaseHash))
  assert.equal(path.dirname(built.bridgeJar), path.dirname(built.agentJar))
  const firstArtifact = await fs.readFile(built.agentJar)
  const firstStat = await fs.stat(built.agentJar)
  const rebuilt = await buildObserverGate({ outputDirectory: path.join(directory, 'build') })
  assert.equal(rebuilt.agentJar, built.agentJar)
  assert.equal(rebuilt.bridgeJar, built.bridgeJar)
  assert.deepEqual(await fs.readFile(built.agentJar), firstArtifact)
  assert.equal((await fs.stat(built.agentJar)).mtimeMs, firstStat.mtimeMs)
  const control = path.join(directory, 'observer-gate.control')
  await fs.writeFile(control, 'HOLD\n')
  const cp = [built.agentJar, built.bridgeJar, built.asmJar, built.testClasses].join(path.delimiter)
  const requests = await run('java', ['-Xverify:all', '-cp', cp, 'observergate.bridge.VanillaUpdatesTest', path.join(directory, 'requests')], { timeout: 30000 })
  assert.match(requests.stdout, /VANILLA_REQUEST_GUARDS_AND_NO_REPLAY/)
  const result = await run('java', ['-Xverify:all', '-cp', cp, 'GateBehaviorTest', built.targetJar, control], { timeout: 30000 })
  assert.match(result.stdout, /OFF HOLD_START HOLD_TICK FALLING MISSING CORRUPT/)
  const behavior = JSON.parse(await fs.readFile(path.join(directory, 'observer-gate-status.json'), 'utf8'))
  assert.equal(behavior.suppressedTicks, 2)
  assert.equal(behavior.suppressedSignals, 2)
  assert.equal(behavior.fallingTicksPassed, 1)
  assert.equal(behavior.unsavedMarks, 2)
  const evidence = (await fs.readFile(path.join(directory, 'observer-gate-events.jsonl'), 'utf8')).trim().split('\n').map(line => JSON.parse(line))
  assert.equal(evidence.filter(event => event.type === 'suppressed-tick').length, 2)
  assert.equal(evidence.filter(event => event.type === 'consumed-tick-chunk-dirty').length, 2)
  assert.ok(evidence.filter(event => event.type.startsWith('suppressed-')).every(event => event.activeMode === 'HOLD' && event.x === 64 && event.y === -60 && event.z === 0))
  const smoke = await run('java', ['-Xverify:all', `-javaagent:${built.agentJar}=${control}`, '-cp', built.testClasses, 'GateClassLoaderTest', built.targetJar, built.libraryDirectory, control], { timeout: 30000 })
  assert.match(smoke.stdout, /BOOTSTRAP_VISIBLE_AND_HOOKS_READY/)
  const status = JSON.parse(await fs.readFile(path.join(directory, 'observer-gate-status.json'), 'utf8'))
  assert.equal(status.hooksReady, true)
  assert.equal(status.controlValid, true)
  assert.equal(typeof status.pid, 'number')
  assert.equal(built.targetJarSha256, 'de9538d2497c8f4174805f3fcedb8ade3060446aa203f351b820ea5bd04adbf4')
  await assert.rejects(run('java', [`-javaagent:${built.agentJar}=${control}`, '-cp', built.testClasses, 'GateClassLoaderTest', built.targetJar, built.libraryDirectory, control, 'reject'], { timeout: 30000 }), error => error.code === 71 && /transform rejected/.test(error.stderr))
  await fs.writeFile(control, 'BROKEN\n')
  await assert.rejects(run('java', [`-javaagent:${built.agentJar}=${control}`, '-cp', built.testClasses, 'GateClassLoaderTest', built.targetJar, built.libraryDirectory, control], { timeout: 30000 }), error => error.code !== 0 && /Invalid observer gate control/.test(error.stderr))
  await fs.appendFile(built.bridgeJar, 'corrupted-artifact')
  const corruptedArtifact = await fs.readFile(built.bridgeJar)
  await assert.rejects(buildObserverGate({ outputDirectory: path.join(directory, 'build') }), /release checksum mismatch/)
  assert.deepEqual(await fs.readFile(built.bridgeJar), corruptedArtifact)
})
